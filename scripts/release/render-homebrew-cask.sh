#!/usr/bin/env bash
# Render the Homebrew cask for the Sigil Mac app from the DMG a release built.
#
# Usage: scripts/release/render-homebrew-cask.sh <version> <repo-slug> <out-file> <dmg>
#   scripts/release/render-homebrew-cask.sh 0.2.0 RainnWorks/sigil dist/sigil-app.rb build/mac/Sigil-0.2.0.dmg
#
# The file is written whole rather than line-edited, so the tap never holds a
# half-updated cask, and the tap needs nothing in place before the first release.
#
# The cask is `sigil-app`, not `sigil`, because the tap's `sigil` is the CLI
# formula. A formula and a cask of the same name both resolve, but then every
# `brew install sigil` prints a warning about which one it picked.
set -euo pipefail

if [[ $# -lt 4 ]]; then
  echo "usage: $0 <version> <repo-slug> <out-file> <dmg>" >&2
  exit 1
fi

VERSION="${1#v}"
REPO_SLUG="$2"
OUT_FILE="$3"
DMG="$4"

[[ -f "$DMG" ]] || { echo "no such file: $DMG" >&2; exit 1; }

if command -v sha256sum >/dev/null 2>&1; then
  SHA="$(sha256sum "$DMG" | cut -d' ' -f1)"
else
  SHA="$(shasum -a 256 "$DMG" | cut -d' ' -f1)"
fi

mkdir -p "$(dirname "$OUT_FILE")"
cat > "$OUT_FILE" <<EOF
# Generated by scripts/release/render-homebrew-cask.sh for ${VERSION}.
cask "sigil-app" do
  version "${VERSION}"
  sha256 "${SHA}"

  url "https://github.com/${REPO_SLUG}/releases/download/v#{version}/Sigil-#{version}.dmg"
  name "Sigil"
  desc "Menubar configurator for the Sigil approval daemon"
  homepage "https://github.com/${REPO_SLUG}"

  livecheck do
    url :url
    strategy :github_latest
  end

  # The app updates itself through Sparkle, so brew upgrade leaves it alone.
  auto_updates true
  depends_on macos: :tahoe

  app "Sigil.app"

  zap trash: [
    "~/Library/Caches/works.rainn.sigil.mac",
    "~/Library/HTTPStorages/works.rainn.sigil.mac",
    "~/Library/Preferences/works.rainn.sigil.mac.plist",
  ]
end
EOF

echo "wrote $OUT_FILE"
